test("without one mode flag, the run prints its usage and reads and writes nothing", () => {
  const files = tree({ yaml: yamlOutOfStep });
  withTree(files, (root) => {
    for (const args of [
      [],
      ["--fix"],
      ["--check", "--write"],
      ["--write", "x"],
    ]) {
      const result = run(args, root);
      assert.equal(result.code, 2, JSON.stringify(args));
      assert.equal(result.error, "usage: sync-config.mjs --check | --write");
      assert.equal(result.log, "");
    }
    assert.deepEqual(readAll(root, files), bytes(files));
  });
});

test("findRegions gives each region the lines of its markers, its indentation and header", () => {
  const { spans, errors } = findRegions(YAML, YAML_LINES, ["steps"]);
  assert.deepEqual(errors, []);
  assert.deepEqual(spans.get("steps"), {
    open: 3,
    close: 6,
    indent: "      ",
    header: `generated by scripts/sync-config.mjs from ${STEPS.source}; edit the source, then run --write`,
  });
});

