// sync-config.test.mjs — the generated regions of configuration files: what
// `--check` and `--write` read, what they refuse, and what they write.
//
// Run:  node --test scripts/tests/sync-config.test.mjs
//
// The cells run `main` on a fixture git work tree with `packages/` and two
// regions: one in a `.properties` file rendered from the package walk, one
// constant and indented as in a workflow. Every refusal of a run that could
// write is asserted to write nothing, with another region of the tree out of
// step, so a write that slipped through would show.

import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

import { withoutGitEnv } from "../git-env.mjs";
import { packages } from "../repo-model.mjs";
import { REGIONS, findRegions, lineDiff, main } from "../sync-config.mjs";

const repoRoot = dirname(dirname(dirname(fileURLToPath(import.meta.url))));

const PROPS = "conf/sonar.properties";
const YAML = "conf/workflow.yml";

/** A region from the package walk, and a constant one at a YAML indentation. */
const MODULES = {
  name: "modules",
  file: PROPS,
  source: "packages/*/package.json",
  render: (root) => [
    `sonar.modules=${packages(root)
      .map((pkg) => pkg.name)
      .join(",")}`,
  ],
};
const STEPS = {
  name: "steps",
  file: YAML,
  source: "the build's step list",
  render: () => ["      - one", "      - two"],
};
const FIXTURE_REGIONS = [MODULES, STEPS];

const open = (name, indent = "", source = "the fixture") =>
  `${indent}# >>> sync-config: ${name} — generated by scripts/sync-config.mjs from ${source}; edit the source, then run --write`;
const close = (name, indent = "") => `${indent}# <<< sync-config: ${name}`;

const PROPS_LINES = [
  "# The fixture's settings.",
  "sonar.projectKey=fx",
  open("modules", "", MODULES.source),
  "sonar.modules=a,b",
  close("modules"),
  "sonar.sources=src",
  "",
];
const YAML_LINES = [
  "jobs:",
  "  build:",
  "    steps:",
  open("steps", "      ", STEPS.source),
  "      - one",
  "      - two",
  close("steps", "      "),
  "  after: true",
  "",
];

/** A tree in step: two packages, and each region holding what it renders. */
const tree = ({ props = PROPS_LINES, yaml = YAML_LINES } = {}) => ({
  "packages/a/package.json": JSON.stringify({ name: "@fx/a" }),
  "packages/b/package.json": JSON.stringify({ name: "@fx/b" }),
  [PROPS]: props.join("\n"),
  [YAML]: yaml.join("\n"),
});

/** The same tree with the YAML region out of step. */
const yamlOutOfStep = YAML_LINES.map((line) =>
  line === "      - two" ? "      - three" : line,
);

/**
 * Builds `files` as a git work tree under a fresh directory, runs `body` on
 * it, removes it. A file given as a Buffer is written byte for byte.
 */
function withTree(files, body) {
  const root = mkdtempSync(join(tmpdir(), "sync-config-"));
  try {
    for (const [file, text] of Object.entries(files)) {
      mkdirSync(dirname(join(root, file)), { recursive: true });
      writeFileSync(join(root, file), text);
    }
    const env = withoutGitEnv(process.env);
    execFileSync("git", ["init", "-q"], { cwd: root, env });
    execFileSync("git", ["add", "-A"], { cwd: root, env });
    return body(root);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

const readAll = (root, files) =>
  Object.fromEntries(
    Object.keys(files).map((file) => [file, readFileSync(join(root, file))]),
  );
const bytes = (files) =>
  Object.fromEntries(
    Object.entries(files).map(([file, text]) => [file, Buffer.from(text)]),
  );

/** Runs `main` and keeps what it prints. */
function run(args, root, regions = FIXTURE_REGIONS) {
  const log = [];
  const error = [];
  const code = main(args, root, regions, {
    log: (line) => log.push(line),
    error: (line) => error.push(line),
  });
  return { code, log: log.join("\n"), error: error.join("\n") };
}

/** A refusal: the run fails with `message`, and neither file changes. */
function refused(files, message, regions = FIXTURE_REGIONS) {
  withTree(files, (root) => {
    for (const mode of ["--check", "--write"]) {
      const result = run([mode], root, regions);
      assert.equal(result.code, 1, `${mode}: ${result.log}`);
      assert.match(result.error, message);
      assert.match(result.error, /nothing written/);
    }
    assert.deepEqual(readAll(root, files), bytes(files));
  });
}

test("CONTROL — --check passes a tree whose regions hold what they render", () => {
  withTree(tree(), (root) => {
    const result = run(["--check"], root);
    assert.equal(result.code, 0, result.error);
    assert.match(
      result.log,
      /✓ sync-config: 2 region\(s\) in 2 file\(s\) in step with their sources/,
    );
  });
});

for (const [name, edit] of Object.entries({
  "an edited line": (lines) =>
    lines.map((line) =>
      line === "sonar.modules=a,b" ? "sonar.modules=a" : line,
    ),
  "a deleted line": (lines) =>
    lines.filter((line) => line !== "sonar.modules=a,b"),
  "an added line": (lines) =>
    lines.flatMap((line) =>
      line === "sonar.modules=a,b" ? [line, "sonar.added=1"] : [line],
    ),
})) {
  test(`a hand change inside a region — ${name} — fails --check, which names it, shows the difference and writes nothing`, () => {
    const files = tree({ props: edit(PROPS_LINES) });
    withTree(files, (root) => {
      const result = run(["--check"], root);
      assert.equal(result.code, 1);
      assert.match(
        result.log,
        /differs: conf\/sonar\.properties — region "modules"/,
      );
      assert.match(result.log, /^ {4}[-+] /m);
      assert.match(result.error, /1 of 2 region\(s\) in 2 file\(s\) differ/);
      assert.deepEqual(readAll(root, files), bytes(files));
    });
  });
}

test("a region follows its source: a new package fails --check, and --write takes it in", () => {
  withTree(
    { ...tree(), "packages/c/package.json": JSON.stringify({ name: "@fx/c" }) },
    (root) => {
      assert.equal(run(["--check"], root).code, 1);
      assert.equal(run(["--write"], root).code, 0);
      assert.ok(
        readFileSync(join(root, PROPS), "utf8").includes(
          "sonar.modules=a,b,c\n",
        ),
      );
      assert.equal(run(["--check"], root).code, 0);
    },
  );
});

test("--write rewrites the regions and nothing else, and a second --write changes nothing", () => {
  const props = [
    "sonar.projectKey=changed-by-hand",
    open("modules", "", MODULES.source),
    "sonar.modules=stale",
    "sonar.extra=stale",
    close("modules"),
    "sonar.sources=lib",
    "",
  ];
  withTree(tree({ props, yaml: yamlOutOfStep }), (root) => {
    const first = run(["--write"], root);
    assert.equal(first.code, 0, first.error);
    assert.match(first.log, /rewrote 2$/m);

    assert.equal(
      readFileSync(join(root, PROPS), "utf8"),
      [
        "sonar.projectKey=changed-by-hand",
        open("modules", "", MODULES.source),
        "sonar.modules=a,b",
        close("modules"),
        "sonar.sources=lib",
        "",
      ].join("\n"),
    );
    assert.equal(readFileSync(join(root, YAML), "utf8"), YAML_LINES.join("\n"));

    const written = readAll(root, tree());
    const second = run(["--write"], root);
    assert.equal(second.code, 0);
    assert.match(second.log, /in step with their sources/);
    assert.deepEqual(readAll(root, tree()), written);
  });
});

test("two regions of one file are both rewritten, the upper one changing its length", () => {
  const TAIL = {
    name: "tail",
    file: PROPS,
    source: "the tail",
    render: () => ["sonar.tail=1"],
  };
  const props = [
    "sonar.projectKey=fx",
    open("modules", "", MODULES.source),
    "x=1",
    "x=2",
    "x=3",
    close("modules"),
    "between=1",
    open("tail", "", TAIL.source),
    "sonar.tail=0",
    close("tail"),
    "",
  ];
  withTree(tree({ props }), (root) => {
    const result = run(["--write"], root, [...FIXTURE_REGIONS, TAIL]);
    assert.equal(result.code, 0, result.error);
    assert.equal(
      readFileSync(join(root, PROPS), "utf8"),
      [
        "sonar.projectKey=fx",
        open("modules", "", MODULES.source),
        "sonar.modules=a,b",
        close("modules"),
        "between=1",
        open("tail", "", TAIL.source),
        "sonar.tail=1",
        close("tail"),
        "",
      ].join("\n"),
    );
  });
});

// Each departure from "one ordered pair of a known name", planted in the
// properties file while the YAML region is out of step.
const INNER = {
  name: "inner",
  file: PROPS,
  source: "the inner",
  render: () => ["sonar.inner=1"],
};
const MARKER_STATES = {
  "a missing opening marker": [
    (lines) =>
      lines.filter((line) => !line.startsWith("# >>> sync-config: modules")),
    /region "modules" needs one opening and one closing marker, and has 0 and 1/,
  ],
  "a missing closing marker": [
    (lines) => lines.filter((line) => line !== close("modules")),
    /region "modules" needs one opening and one closing marker, and has 1 and 0/,
  ],
  "a repeated opening marker": [
    (lines) => [open("modules", "", MODULES.source), ...lines],
    /region "modules" needs one opening and one closing marker, and has 2 and 1/,
  ],
  "a repeated closing marker": [
    (lines) => [...lines, close("modules")],
    /region "modules" needs one opening and one closing marker, and has 1 and 2/,
  ],
  "markers in reverse order": [
    (lines) =>
      lines.map((line) =>
        line.startsWith("# >>> sync-config: modules")
          ? close("modules")
          : line === close("modules")
            ? open("modules", "", MODULES.source)
            : line,
      ),
    /region "modules" closes before it opens/,
  ],
  "markers of another region nested inside": [
    (lines) =>
      lines.flatMap((line) =>
        line === "sonar.modules=a,b"
          ? [
              open("inner", "", INNER.source),
              "sonar.inner=1",
              close("inner"),
              line,
            ]
          : [line],
      ),
    /a marker of region "inner" inside region "modules"/,
    [...FIXTURE_REGIONS, INNER],
  ],
  "a marker of a name no region has": [
    (lines) => [...lines, open("ghost"), close("ghost")],
    /a marker of region "ghost", which this file does not hold/,
  ],
  "a marker of a region another file holds": [
    (lines) => [...lines, open("steps"), close("steps")],
    /a marker of region "steps", which this file does not hold/,
  ],
  "markers at different indentations": [
    (lines) =>
      lines.map((line) => (line === close("modules") ? `  ${line}` : line)),
    /region "modules" closes at another indentation than it opens/,
  ],
  "an opening marker that names no source": [
    (lines) =>
      lines.map((line) =>
        line.startsWith("# >>> sync-config: modules")
          ? "# >>> sync-config: modules — generated, see the script"
          : line,
      ),
    /the opening marker of region "modules" does not name its source, packages\/\*\/package\.json/,
  ],
};

for (const [name, [plant, message, regions]] of Object.entries(MARKER_STATES)) {
  test(`marker state: ${name} fails the run and writes nothing`, () => {
    refused(
      tree({ props: plant(PROPS_LINES), yaml: yamlOutOfStep }),
      message,
      regions,
    );
  });
}

for (const lookalike of [
  "#>>> sync-config: modules",
  "// >>> sync-config: modules",
  "# >>> sync-config:modules",
  "# >>> sync-config: Modules",
  "# >>> sync-config: modules",
  "# <<<sync-config: modules",
  "# <<< sync-config: modules trailing",
  "  # >>> sync-config: modules trailing",
  "# >> sync-config: modules",
  "# >>> SYNC-CONFIG: modules",
  "# >>> sync_config: modules",
  "# sync-config >>> modules",
  "sonar.x=1 # >>> sync-config: modules — a header",
]) {
  test(`a line that names a marker in another form fails the run: ${lookalike}`, () => {
    refused(
      tree({
        props: [...PROPS_LINES.slice(0, -1), lookalike, ""],
        yaml: yamlOutOfStep,
      }),
      /a line that names a sync-config marker but is not one/,
    );
  });
}

