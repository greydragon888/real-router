test("on the repository, the command line checks exactly the regions REGIONS lists, and refuses no flag", () => {
  const script = join(repoRoot, "scripts", "sync-config.mjs");
  const files = new Set(REGIONS.map((region) => region.file)).size;
  const check = spawnSync(process.execPath, [script, "--check"], {
    encoding: "utf8",
  });
  assert.equal(check.status, 0, check.stderr);
  assert.equal(
    check.stdout,
    `✓ sync-config: ${REGIONS.length} region(s) in ${files} file(s) in step with their sources\n`,
  );

  const bare = spawnSync(process.execPath, [script], { encoding: "utf8" });
  assert.equal(bare.status, 2);
  assert.equal(bare.stderr, "usage: sync-config.mjs --check | --write\n");
});
